// Runs every tricky scenario against the permission rules.
// Launch gate: every scenario must pass, and no safety scenario may ever run on its own.
//   node tests/run-tests.mjs

import { writeFileSync, mkdirSync } from 'node:fs';
import { decide, onDeposit } from '../docs/app/rules.js';
import { SCENARIOS, NOW } from '../docs/app/scenarios.js';

const H = 60 * 60 * 1000;

export function check(sc) {
  const fails = [];
  let actual;
  if (sc.kind === 'deposit') {
    const r = onDeposit(sc.deposit, sc.state, NOW);
    const save = r.proposals.find((p) => p.type === 'save');
    const rent = r.proposals.find((p) => p.type === 'rent_jar');
    actual = { proposals: r.proposals.map((p) => `${p.type} $${p.amount}`).join(', ') || 'none', notes: r.notes.map((n) => n.code).join(', ') || 'none' };
    if (sc.expect.note && !r.notes.some((n) => n.code === sc.expect.note)) fails.push(`expected note ${sc.expect.note}`);
    if (sc.expect.proposals !== undefined && r.proposals.length !== sc.expect.proposals) fails.push(`expected ${sc.expect.proposals} proposals, got ${r.proposals.length}`);
    if (sc.expect.firstProposal && r.proposals[0]?.type !== sc.expect.firstProposal) fails.push(`expected ${sc.expect.firstProposal} first`);
    if (sc.expect.saveAmount !== undefined && save?.amount !== sc.expect.saveAmount) fails.push(`expected save $${sc.expect.saveAmount}, got $${save?.amount}`);
    if (sc.expect.rentShare !== undefined && rent?.amount !== sc.expect.rentShare) fails.push(`expected rent share $${sc.expect.rentShare}, got $${rent?.amount}`);
  } else {
    const d = decide(sc.action, sc.state, NOW);
    actual = { outcome: d.outcome, reasons: d.reasons.map((r) => r.code).join(', '), amount: d.amount };
    if (d.outcome !== sc.expect.outcome) fails.push(`expected ${sc.expect.outcome}, got ${d.outcome}`);
    if (sc.expect.reason && !d.reasons.some((r) => r.code === sc.expect.reason)) fails.push(`expected reason ${sc.expect.reason}`);
    if (sc.expect.amount !== undefined && d.amount !== sc.expect.amount) fails.push(`expected amount $${sc.expect.amount}, got $${d.amount}`);
    if (sc.expect.sendAfterHours !== undefined && d.sendAt !== NOW + sc.expect.sendAfterHours * H) fails.push(`expected send after ${sc.expect.sendAfterHours}h`);
    // Safety invariant: anything tagged safety must never run on its own unless the test expects it to
    if (sc.tags.includes('safety') && d.outcome.startsWith('auto') && !sc.expect.outcome.startsWith('auto')) fails.push('SAFETY: ran on its own');
  }
  return { id: sc.id, title: sc.title, tags: sc.tags, pass: fails.length === 0, fails, actual };
}

const results = SCENARIOS.map(check);
const passed = results.filter((r) => r.pass).length;
const safety = results.filter((r) => r.tags.includes('safety'));
const safetyPass = safety.every((r) => r.pass);
const gate = passed === results.length && safetyPass;

const md = `# Test results

Generated by \`node tests/run-tests.mjs\`. Synthetic data only.

**Launch gate: ${gate ? 'PASS' : 'FAIL'}** (${passed} of ${results.length} scenarios pass; safety scenarios ${safetyPass ? 'all pass' : 'FAILING'})

| ID | Scenario | Tags | Result | What Pocket Pilot did |
| --- | --- | --- | --- | --- |
${results.map((r) => `| ${r.id} | ${r.title} | ${r.tags.join(', ')} | ${r.pass ? 'Pass' : 'FAIL: ' + r.fails.join('; ')} | ${r.actual.outcome ? `${r.actual.outcome} (${r.actual.reasons})` : `${r.actual.proposals}; notes: ${r.actual.notes}`} |`).join('\n')}
`;

mkdirSync('data', { recursive: true });
writeFileSync('data/test-results.md', md);
writeFileSync('data/test-results.json', JSON.stringify({ gate, passed, total: results.length, results }, null, 2));
console.log(md);
if (!gate) { console.error('Launch gate failed.'); process.exit(1); }
